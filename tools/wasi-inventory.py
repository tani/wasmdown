#!/usr/bin/env python3
"""Generate the WASI ABI inventories from the PINNED specification sources.

The denominator of "supported" is the pinned WITX / WIT, never the Lisp
implementation registry: this tool parses the vendored specification trees
(``specs/wasi/preview1``, ``specs/wasi/wasi-wit-<version>``) with its own
independent reader and writes

    specs/wasi/preview1/INVENTORY.md
    specs/wasi/preview2/INVENTORY.md

Each entry names the concrete binding that must implement it and the
behavioral check that exercises it (see ``tools/wasi-coverage.json`` once a
lane has run; this file only fixes the census).

Usage: tools/wasi-inventory.py [--check]
    --check  fail if a generated inventory is stale
"""
import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPECS = os.path.join(ROOT, "specs", "wasi")


# ---------------------------------------------------------------- preview1
def tokenize(text):
    text = re.sub(r";[^\n]*", "", text)  # notes / line comments
    return re.findall(r'\(|\)|"[^"]*"|[^\s()]+', text)


def parse_sexprs(tokens):
    stack = [[]]
    for tok in tokens:
        if tok == "(":
            stack.append([])
        elif tok == ")":
            done = stack.pop()
            stack[-1].append(done)
        else:
            stack[-1].append(tok)
    return stack[0]


def head(node):
    return node[0] if isinstance(node, list) and node else None


def flatten(node):
    if isinstance(node, list):
        return "(" + " ".join(flatten(n) for n in node) + ")"
    return str(node)


def find(node, name):
    return [n for n in node if isinstance(n, list) and head(n) == name]


def preview1_inventory():
    path = os.path.join(SPECS, "preview1", "witx", "wasi_snapshot_preview1.witx")
    tree = parse_sexprs(tokenize(open(path).read()))
    module = find(tree, "module")[0]
    funcs = []
    for node in find(module, "@interface"):
        if len(node) < 2 or node[1] != "func":
            continue
        export = find(node, "export")
        name = export[0][1].strip('"') if export else "?"
        result = find(node, "result")
        rtype = flatten(result[0][1:]) if result else ""
        params = ["$" + p[1] if len(p) > 1 else "?" for p in find(node, "param")]
        funcs.append((name, params, rtype))
    # typenames: enums, flags, structs, handles, arrays, aliases
    tn_path = os.path.join(SPECS, "preview1", "witx", "typenames.witx")
    ttree = parse_sexprs(tokenize(open(tn_path).read()))
    typedecls = {}
    for node in find(ttree, "typename"):
        tname = node[1].lstrip("$")
        typedecls[tname] = node[2] if len(node) > 2 else []
    enums, flags, structs, handles, aliases = {}, {}, {}, [], {}
    for name, decl in typedecls.items():
        if not isinstance(decl, list):
            aliases[name] = str(decl)
        elif head(decl) == "enum":
            enums[name] = [c[1] for c in find(decl, "enum")]
        elif head(decl) == "flags":
            flags[name] = [c[1] for c in find(decl, "flag")]
        elif head(decl) == "struct":
            structs[name] = [(f[1], " ".join(map(str, f[2:]))) for f in find(decl, "field")]
        elif head(decl) == "handle":
            handles.append(name)
        else:
            aliases[name] = " ".join(map(str, decl))
    return funcs, enums, flags, structs, handles, aliases


P1_BINDINGS = {f: f"wasi-preview1.lisp %p1-import-{f.replace('_', '-')}" for f in
               "args_get args_sizes_get environ_get environ_sizes_get clock_res_get clock_time_get "
               "fd_advise fd_allocate fd_close fd_datasync fd_fdstat_get fd_fdstat_set_flags "
               "fd_fdstat_set_rights fd_filestat_get fd_filestat_set_size fd_filestat_set_times "
               "fd_pread fd_prestat_get fd_prestat_dir_name fd_pwrite fd_read fd_readdir fd_renumber "
               "fd_seek fd_sync fd_tell fd_write path_create_directory path_filestat_get "
               "path_filestat_set_times path_link path_open path_readlink path_remove_directory "
               "path_rename path_symlink path_unlink_file poll_oneoff proc_exit proc_raise "
               "sched_yield random_get sock_accept sock_recv sock_send sock_shutdown".split()}


def write_preview1():
    funcs, enums, flags, structs, handles, aliases = preview1_inventory()
    want = set(P1_BINDINGS)
    got = {f[0] for f in funcs}
    missing = sorted(want - got)
    extra = sorted(got - want)
    if missing or extra:
        raise SystemExit(f"preview1 census mismatch: missing={missing} extra={extra} ({len(funcs)} functions)")
    out = ["# WASI Preview1 ABI inventory (generated)"]
    out.append("")
    out.append("Generated by `tools/wasi-inventory.py` from")
    out.append("`specs/wasi/preview1/witx/*.witx` (pinned; see `specs/lock.toml`),")
    out.append("not from the implementation registry. Do not edit by hand.")
    out.append("")
    out.append(f"## Functions ({len(funcs)})")
    out.append("")
    out.append("| export | signature | binding |")
    out.append("|---|---|---|")
    for name, params, rtype in funcs:
        sig = f"({', '.join(params)}) -> {rtype}"
        out.append(f"| `{name}` | `{sig}` | `{P1_BINDINGS[name]}` |")
    out.append("")
    out.append("## Types")
    out.append("")
    out.append(f"- handles: {', '.join(sorted(handles))}")
    for kind, table in (("enum", enums), ("flags", flags)):
        out.append(f"- {kind}s: {len(table)}")
        for name in sorted(table):
            out.append(f"  - `{name}`: {', '.join(map(str, table[name]))}")
    out.append(f"- structs: {len(structs)}")
    for name in sorted(structs):
        fields = ", ".join(f"{n} {t}" for n, t in structs[name])
        out.append(f"  - `{name}`: {fields}")
    out.append(f"- aliases: {len(aliases)}")
    for name in sorted(aliases):
        out.append(f"  - `{name}` = {aliases[name]}")
    out.append("")
    out.append("## Platform-pinned behavior")
    out.append("")
    out.append("- `proc_raise`: a VALID signal discriminant returns `errno::notsup` and never")
    out.append("  signals the hosting SBCL process (the in-process embedding limitation;")
    out.append("  matches the pinned Wasmtime v50.0.1 Preview1 implementation). An invalid")
    out.append("  discriminant is `errno::inval`.")
    path = os.path.join(SPECS, "preview1", "INVENTORY.md")
    return path, "\n".join(out) + "\n", len(funcs)


# ---------------------------------------------------------------- preview2
PKGS = ["cli", "clocks", "filesystem", "http", "io", "random", "sockets"]


def strip_comments(text):
    return re.sub(r"//[^\n]*", "", text)


def wit_surface(path):
    """Very small independent WIT reader: interfaces, resources, functions,
    worlds, and each declaration's stability gate."""
    src = strip_comments(open(path).read())
    version = None
    m = re.search(r"package\s+wasi:([a-z-]+)@([0-9.]+)\s*;", src)
    if m:
        version = m.group(2)
    ifaces = []
    for m in re.finditer(r"(?:@since\(version = ([0-9.]+)\)\s*)?interface\s+([a-z0-9-]+)\s*\{", src):
        start = m.end()
        depth, i = 1, start
        while i < len(src) and depth:
            if src[i] == "{":
                depth += 1
            elif src[i] == "}":
                depth -= 1
            i += 1
        body = src[start:i - 1]
        ifaces.append((m.group(2), body))
    worlds = []
    for m in re.finditer(r"world\s+([a-z0-9-]+)\s*\{", src):
        start = m.end()
        depth, i = 1, start
        while i < len(src) and depth:
            if src[i] == "{":
                depth += 1
            elif src[i] == "}":
                depth -= 1
            i += 1
        worlds.append((m.group(1), src[start:i - 1]))
    result = []
    for name, body in ifaces:
        resources, funcs = [], []
        for rm in re.finditer(r"(?:@since\(version = ([0-9.]+)\)\s*)?(?:@unstable\([^)]*\)\s*)?resource\s+([a-z0-9-]+)\s*\{", body):
            start = rm.end()
            depth, i = 1, start
            while i < len(body) and depth:
                if body[i] == "{":
                    depth += 1
                elif body[i] == "}":
                    depth -= 1
                i += 1
            rbody = body[start:i - 1]
            methods = [f"{rm.group(2)}.{mm.group(2)}" for mm in
                       re.finditer(r"(?:@since\(version = ([0-9.]+)\)\s*)?(?:static\s+)?([a-z0-9-]+):\s+(?:static\s+)?func", rbody)]
            methods += [f"{rm.group(2)}.{mm.group(1)}" for mm in
                        re.finditer(r"(?:@since\(version = ([0-9.]+)\)\s*)?constructor\(([a-z0-9-]+)\)", rbody)]
            # the implicit resource drop is part of the ABI
            methods.append(f"{rm.group(2)}.[resource-drop]")
            resources.append((rm.group(2), sorted(set(methods))))
        flat = re.sub(r"(?:@since\(version = ([0-9.]+)\)\s*)?(?:@unstable\([^)]*\)\s*)?resource\s+[a-z0-9-]+\s*\{", "", body)
        for mm in re.finditer(r"(?:@since\(version = ([0-9.]+)\)\s*)?(?:@unstable\([^)]*\)\s*)?([a-z0-9-]+):\s+func", body):
            funcs.append(mm.group(2))
        result.append((name, resources, funcs))
    return version, result, worlds


def write_preview2(versions):
    out = ["# WASI 0.2 stable interface inventory (generated)", ""]
    out.append("Generated by `tools/wasi-inventory.py` from the vendored release trees")
    out.append("indexed by `specs/wasi/index.txt` (pins in `specs/lock.toml`).")
    out.append("The implementation registry is never the denominator. Do not edit by hand.")
    out.append("")
    index = {}
    for line in open(os.path.join(SPECS, "index.txt")):
        if line.startswith("#"):
            continue
        version, pkg, rel = line.rstrip("\n").split("\t")
        if "/deps/" in rel:
            continue  # release-shipped copies of a dependency, not a new surface
        index.setdefault(version, {}).setdefault(pkg, []).append(rel)
    totals = {}
    for v in versions:
        out.append(f"## {v}")
        out.append("")
        pkg_rows = index.get(v, {})
        grand = 0
        for pkg in PKGS:
            files = sorted(pkg_rows.get(pkg, []))
            if not files:
                continue
            ifaces, worlds = {}, {}
            for rel in files:
                ver, isurf, wsurf = wit_surface(os.path.join(SPECS, rel))
                for nm, resources, funcs in isurf:
                    iface = ifaces.setdefault(nm, {"resources": {}, "funcs": set()})
                    iface["funcs"].update(funcs)
                    for rname, methods in resources:
                        iface["resources"].setdefault(rname, set()).update(methods)
                for nm, body in wsurf:
                    worlds.setdefault(nm, set()).update(
                        re.findall(r"(import|export)\s+wasi:([a-z-]+)/([a-z0-9-]+)@([0-9.]+)", body)
                        and [m[2] for m in re.findall(r"(import|export)\s+wasi:([a-z-]+)/([a-z0-9-]+)@([0-9.]+)", body)])
            out.append(f"### wasi:{pkg} ({v})")
            out.append("")
            out.append("| interface | functions | resources |")
            out.append("|---|---|---|")
            count = 0
            for nm in sorted(ifaces):
                iface = ifaces[nm]
                nfun = len(iface["funcs"])
                nres = sum(len(ms) for ms in iface["resources"].values())
                count += nfun + nres
                res = ", ".join(f"{r}({len(m)})" for r, m in sorted(iface["resources"].items()))
                out.append(f"| `{nm}` | {nfun} | {res or '-'} |")
            out.append("")
            if worlds:
                out.append("worlds: " + ", ".join(f"`{w}`" for w in sorted(worlds)))
                out.append("")
            grand += count
        totals[v] = grand
        out.append(f"`wasi:*@{v}` surface: {grand} function/resource-method entries.")
        out.append("")
    path = os.path.join(SPECS, "preview2", "INVENTORY.md")
    return path, "\n".join(out) + "\n", totals


def main():
    check = "--check" in sys.argv[1:]
    versions = ["0.2.0", "0.2.1", "0.2.2", "0.2.3", "0.2.4", "0.2.5", "0.2.6",
                "0.2.7", "0.2.8", "0.2.9", "0.2.10", "0.2.11", "0.2.12"]
    stale = []
    for path, text, _ in (write_preview1(),):
        old = open(path).read() if os.path.exists(path) else None
        if check:
            if old != text:
                stale.append(path)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, "w").write(text)
            print(f"wrote {os.path.relpath(path, ROOT)}")
    path, text, totals = write_preview2(versions)
    old = open(path).read() if os.path.exists(path) else None
    if check:
        if old != text:
            stale.append(path)
    else:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, "w").write(text)
        print(f"wrote {os.path.relpath(path, ROOT)}: " + ", ".join(f"{v}={n}" for v, n in totals.items()))
    if stale:
        raise SystemExit("stale inventory: " + ", ".join(os.path.relpath(p, ROOT) for p in stale))


if __name__ == "__main__":
    main()
