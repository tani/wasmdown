#!/usr/bin/env python3
"""Run only the upstream network cases (wasi:http / wasi:sockets).

The ordinary lane (tools/run-wasi-testsuite.py) deliberately skips these
under the main-branch exclusion policy. This branch (feat/http) declares the
full network surface, so this tool selects the inverse subset:

  * every test whose JSON lists the `http` or `sockets` proposal is admitted;
  * every other test is skipped by a generated expectation with an explicit
    `non-network` reason;
  * a `--reference` run uses the upstream Wasmtime adapter to prove the host
    environment (loopback TCP, HTTP framing) itself works.

Exit codes: 0 all admitted network tests pass; 1 measured failures; 2 setup
problem (missing pinned checkout, missing adapter/reference runtime).
"""
import argparse
import json
import os
import pathlib
import re
import subprocess
import sys
import tempfile
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
LOCK = ROOT / "specs" / "lock.toml"
PIN_SECTION = "suite.wasi-testsuite"
DEFAULT_DIR = ROOT / ".cache" / "wasi-testsuite"
NETWORK_PROPOSALS = {"http", "sockets"}


def abort(msg):
    print(msg, file=sys.stderr)
    sys.exit(2)


def pin():
    with LOCK.open("rb") as fh:
        data = tomllib.load(fh)
    entry = data.get("suite", {}).get("wasi-testsuite")
    if not entry:
        abort(f"specs/lock.toml has no [{PIN_SECTION}]")
    return entry


def checkout(cli):
    path = pathlib.Path(
        cli or os.environ.get("WASI_TESTSuite_DIR")
        or os.environ.get("WASI_TESTSUITE_DIR") or DEFAULT_DIR
    ).expanduser().resolve()
    if not (path / "run-tests").exists():
        abort(f"wasi-testsuite checkout missing at {path}; run "
              f"tools/setup-network-tests.sh or set WASI_TESTSuite_DIR")
    return path


def suites(root):
    found = []
    for manifest in sorted((root / "tests").glob("*/testsuite/*/manifest.json")):
        data = json.loads(manifest.read_text(encoding="utf-8"))
        found.append((manifest.parent, data["name"], data["version"]))
    if not found:
        abort(f"no manifest.json under {root}/tests")
    return found


def config(test_dir, name):
    p = test_dir / f"{name}.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else {}


def is_network(cfg, only=None):
    proposals = set(cfg.get("proposals") or [])
    if only is not None:
        return bool(proposals & only)
    return bool(proposals & NETWORK_PROPOSALS)


def write_expectations(path, found, only=None):
    lines = [
        "# Generated by tools/run-wasi-network-tests.py: the inverse of the",
        "# main-lane declarations. Only http/sockets cases run; every other",
        "# test is skipped as non-network (not as a failure).",
        "version = 1",
        "",
    ]
    total = admitted = 0
    for test_dir, suite_name, _version in found:
        skips = []
        for wasm in sorted(test_dir.glob("*.wasm")):
            total += 1
            if is_network(config(test_dir, wasm.stem), only):
                admitted += 1
            else:
                skips.append(wasm.stem)
        if skips:
            lines += ["[[suite]]", f"name = {json.dumps(suite_name)}", ""]
            for name in skips:
                lines += ["[[suite.test]]",
                          f"name = {json.dumps(name)}",
                          'action = "skip"', ""]
    path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    return total, admitted


def run(root, pin_entry, adapter, expectations, json_out, reference):
    cmd = [sys.executable, str(root / "run-tests"),
           "--runtime-adapter", str(adapter),
           "--expectations", str(expectations),
           "--json-output-location", str(json_out),
           "--disable-colors"]
    env = dict(os.environ)
    env["WASMDOWN_ROOT"] = str(ROOT)
    if reference:
        wasmtime = env.get("WASMTIME")
        if not wasmtime:
            abort("--reference needs WASMTIME=<path>; run tools/setup-network-tests.sh")
        env["WASMTIME"] = wasmtime
    proc = subprocess.run(cmd, cwd=str(root), capture_output=True, text=True,
                          env=env)
    print(proc.stdout, end="")
    if proc.stderr:
        print(proc.stderr, end="", file=sys.stderr)
    return proc.returncode


def summarize(raw, path):
    results = raw.get("results", [])
    rows = []
    for suite in results:
        for test in suite.get("tests", []):
            if not test.get("executed"):
                continue
            rows.append((suite["name"], test["name"], test["outcome"],
                         " | ".join(test.get("failures") or [])[:300]))
    passed = sum(1 for r in rows if r[2] == "pass")
    failed = sum(1 for r in rows if r[2] in ("fail", "xpass"))
    lines = ["# WASI network test lane", "",
             f"Admitted network tests executed: {len(rows)}; "
             f"pass {passed}, fail {failed}.", "",
             "| Suite | Test | Outcome | Failure |", "| --- | --- | --- | --- |"]
    for suite, test, outcome, failure in rows:
        lines.append(f"| {suite} | {test} | {outcome} | {failure.replace('|', '/')} |")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir")
    ap.add_argument("--adapter", help="adapter path (default: wasmdown or upstream wasmtime)")
    ap.add_argument("--reference", action="store_true",
                    help="run the upstream Wasmtime adapter instead of wasmdown")
    ap.add_argument("--json-output", default="/tmp/wasi-network-results.json")
    ap.add_argument("--summary", default="/tmp/wasi-network-summary.md")
    ap.add_argument("--proposal", action="append", default=None,
                    metavar="NAME",
                    help="restrict the admitted subset to tests declaring this "
                         "proposal (repeatable, e.g. --proposal sockets)")
    args = ap.parse_args()
    only = set(args.proposal) if args.proposal else None

    entry = pin()
    root = checkout(args.dir)
    head = subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"],
                          capture_output=True, text=True).stdout.strip()
    if head != entry["commit"]:
        abort(f"suite HEAD {head} != pinned {entry['commit']}")
    adapter = pathlib.Path(args.adapter) if args.adapter else (
        root / "adapters" / "wasmtime.py" if args.reference
        else ROOT / "adapters" / "wasmdown.py")
    if not adapter.exists():
        abort(f"adapter missing: {adapter}")

    found = suites(root)
    with tempfile.TemporaryDirectory(prefix="wasi-network-") as tmp:
        expectations = pathlib.Path(tmp) / "expectations.toml"
        raw_path = pathlib.Path(tmp) / "results.json"
        total, admitted = write_expectations(expectations, found, only)
        print(f"network subset: {admitted} admitted / {total} pinned tests; "
              f"adapter={adapter}")
        code = run(root, entry, adapter, expectations, raw_path, args.reference)
        raw = json.loads(raw_path.read_text(encoding="utf-8"))
        summarize(raw, pathlib.Path(args.summary))
        print(f"summary: {args.summary}")
        print(f"json:    {args.json_output}")
        pathlib.Path(args.json_output).write_text(
            json.dumps(raw, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return code


if __name__ == "__main__":
    sys.exit(main())
